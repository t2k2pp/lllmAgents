def build(kind):
    spec = KINDS[kind]
    parts = []
    for name, secs, mirror, color in spec["parts"]:
        for suffix, s in [("", secs)] + ([("_R", mirrored(secs))] if mirror else []):
            ob = loft(name + suffix, s)
            ob["color"] = color
            parts.append(ob)
    body = fuse(parts, kind.capitalize(), spec["voxel"])
    decimate(body, spec["faces"])
    paint_by_parts(body, parts, spec["colors"])
    return body


if __name__ == "__main__":
    clear_scene()
    ob = build(KIND)
    measure(ob)
    render_views(ob, OUT_DIR, KIND)
    export(ob.name, OUT_DIR)
